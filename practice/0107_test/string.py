# 문자열 '20210101Sunny'를 슬라이싱하여 날짜는 date변수에 날씨는 weather 변수에 저장 후 출력 하세요
# [출력]
# date: 20210101, weather: Sunny
sample = '20210101Sunny'

date = sample[0:8]
weather = sample[8:13]

print(f"date:{date}, weather:{weather}") # 쉬워보였는데 f-string 의 "{}" 를 생각못하고, 튜플로 출력하려다 헷갈려짐.



