"""
[예제 11] LU 분해
A = [[2, 6, 2],
     [-3, -8, 0],
     [4, 9, 2]]
"""

# 계수행렬 A 생성
A = matrix([[2, 6, 2], [-3, -8, 0], [4, 9, 2]])

# LU 분해 (부분 피벗팅 포함)
# P: 치환(퍼뮤테이션) 행렬, L: 하삼각행렬, U: 상삼각행렬

# L 하삼각행렬(lower)
# 아랫부분을 제외한 윗부분이 전부 "0"

# U 상삼각행렬(upper)
# 윗부분을 제외한 아래 부분이 전부 "0"



# 행렬 A 를 하삼각행렬 L 과 상삼각 행렬 U  의 곱 을 
# A = LU로 표현하는 것을 LU 분해라고 함. 

P, L, U = A.LU()

print("A =")
print(A)

print("\nP =")
print(P)  # 치환행렬 (행 교환 기록)

print("\nL =")
print(L)  # 하삼각행렬 (대각선이 1)

print("\nU =")
print(U)  # 상삼각행렬

print("\nCheck : P * A == L * U ?")
# (3) 검증: LU 분해가 맞으면 True가 출력됨
print(P * A == L * U)


