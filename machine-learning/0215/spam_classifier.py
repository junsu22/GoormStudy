# --------------------------------------
# 축하합니다! 무료 아이폰 당첨! (spam)
predict_spam("Congratulations! You've won a free iPhone. Click here now!")
# 내일 점심 만나는거지?(ham)
predict_spam("Hey, are we still meeting for lunch tomorrow?")
# 긴급! 계정 폐쇄!(spam)
