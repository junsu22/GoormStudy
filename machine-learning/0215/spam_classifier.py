# ============= 모델 비교 ================================
# 로지스틱 회귀 -------------------------------------
# 모델생성
lr_model = LogisticRegression(max_iter=1000)
# 학습
lr_model.fit(X_train_tfidf, y_train)
# 예측
lr_pred = lr_model.predict(X_test_tfidf)

# SVM (Support Vector Machine) 데이터 사이 깔끔한 경계선을 그어 나누는 모델---------------
