import sklearn
import numpy as np
import pandas as pd
from sklearn.datasets import load_iris
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier
from sklearn.metrics import accuracy_score

# 분할 단계
iris = load_iris()# train 70% test 30% 분할
X_train, X_test, y_train, y_test = train_test_split(iris.data, iris.target, test_size = 0.3, random_state= 1)
dt_clf = DecisionTreeClassifier(random_state=1) # 딕션 트리생성 , 결과 고정
dt_clf.fit(X_train, y_train)  # 학습
pred = dt_clf.predict(X_test) # 테스트 데이터 예측
round(accuracy_score(y_test, pred), 4)  # 정확도 계산

# k-fold 교차검증
# 데이터를 k 개의 fold 로 나누어 k 번 반복 검증
from sklearn.model_selection import KFold
kfold = KFold(n_splits = 5) # 데이터를 5 등분 한다. 5번 반복 검증

iris = load_iris()
feature = iris.data # 입력 feature
label = iris.target # 정답 label

cv_accuracy = []  # fold 의 정확도를 저장할 list
n_iter = 0  # 몇 번째 fold 인지 count
dt_clf = DecisionTreeClassifier(random_state=1)
feature.shape

n_iter = 0  # 카운터 초기화
  # kfold.split(feature): 각 폴드의 학습/검증 인덱스를 순서대로 반환
for train_index, test_index in kfold.split(feature):
  # 피처 분할
  x_train, x_test = feature[train_index], feature[test_index]
  # 레이블 분할
  y_train, y_test = label[train_index], label[test_index]

  dt_clf.fit(x_train, y_train)  # 학습
  pred = dt_clf.predict(x_test) # 예측
  n_iter += 1 # 폴드 카운터 증가
  # 폴드 정확도
  accuracy = np.round(accuracy_score(y_test,pred), 4)
  # 학습데이터 개수
  train_size = x_train.shape[0]
  # 검증데이터 개수
  test_size = x_test.shape[0]

  print('\n{0} 교차 검증 정확도 : {1}, 학습 데이터 크기: {2}, 검증 데이터 크기 : {3}'.format(n_iter, accuracy, train_size, test_size))
  print('#{0} 검증 세트 인덱스 : {1}'.format(n_iter, test_index))
  cv_accuracy.append(accuracy) # 정확도 리스트에 추가

print('\n## 평균 검증 정확도 : ', np.mean(cv_accuracy)) # 낮은 폴드 존재

