  train = iris_df['label'].iloc[train_index]
  test = iris_df['label'].iloc[test_index]
  # 클래스 개수 출력하기 (목표 : 비율이 잘 유지가 되는지 확인)
  print("# 교차 검증:{}".format(n_iter_))
  print("# 학습 레이블 데이터 : \n", train.value_counts())
