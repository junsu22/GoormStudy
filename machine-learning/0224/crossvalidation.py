# 이런 현상이 생기는 이유 : 데이터를 랜덤하게 나누지 않고, 차례대로 클래스 순서대로 잘라버려서 생긴 문제
# shuffle=True를 사용하거나, 분류 문제에서는 StratifiedKFold를 사용하는 것이 더 적절하다.

# 사용하는 이유 : 운 방지 ..(편향 줄이기) 80% 학습 20% 테스트 한 경우 ..
# 쉬운문제들만 테스트 데이터에 들어간 경우 : 성능 좋은것으로 판단.
# 어려운문제들만 테스트 데이터에 들어간 경우 : 성능이 안좋은 모델로 판단.

# 3fold, 5fold... 같은 모델로 시험 3번 , 5번 .... 보기
# 여러번 시험을 봐서 진짜 실력을 본다.  (컨디션 안좋은날, 컨디션 최상의 날 등..)

# 3 fold
kfold = KFold(n_splits=3) # 데이터 3등분
