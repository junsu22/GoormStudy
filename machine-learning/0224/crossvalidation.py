# LOOCV(Leave - One - Out Cross- Validation)
# 데이터 1개만 테스트로 쓰고 나머지 전부를 학습에 사용하는 교차검증
from sklearn.model_selection import LeaveOneOut, cross_val_score

iris = load_iris()
feature = iris.data
label = iris.target
# train 149개 / test 1개
dt_clf = DecisionTreeClassifier(random_state = 1)
loocv = LeaveOneOut()
# 데이터 개수(150개)만큼 반복 수행 → 교차 검증 횟수 = 150
score = cross_val_score(dt_clf, feature, label, cv = loocv)

print('\n## 교차 검증 횟수 :', len(score))  # 150
print('\n## 평균 검증 정확도 :', round(np.mean(score),4)) # 거의 모든 데이터를 학습에 사용해서 편향(bias)이 낮다.

# 좋은점 : 편향이 낮다.
# 나쁜점 : 계산량이 많다.
# 데이터 개수 만큼 학습해야해서 계산량이 많아 실무에서는 많이 안쓰일것 같다.



print('\n## 교차 검증 횟수 :', len(score))
print('\n## 평균 검증 정확도 :', round(np.mean(score),4))

